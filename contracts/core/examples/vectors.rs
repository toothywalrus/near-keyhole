//! Prints the cross-language vectors that hold the TypeScript twin in `lib/src/` to this crate:
//! `cargo run -p keyhole-core --features sha2 --example vectors > fixtures/vectors.json`
use keyhole_core::entry::{self, Entry};
use keyhole_core::ggm::{self, Tree};
use keyhole_core::pnl::{pnl_e6, Book, MAX_FEEDS};
use keyhole_core::Sha2;
use serde_json::{json, Value};

fn hx(b: &[u8]) -> String {
    hex::encode(b)
}

/// A little deterministic generator, so that the vectors need no dependency.
struct Lcg(u64);
impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        self.0 >> 11
    }
}

fn main() {
    let mut r = Lcg(0x6b65_7968_6f6c_65);
    let seed = [7u8; 32];
    let depth = 12u8;
    let t = Tree::build::<Sha2>(&seed, depth);

    let mut windows: Vec<Value> = Vec::new();
    for (a, b) in [(0u32, 0u32), (0, 4095), (1, 1), (5, 9), (24, 191), (1000, 1167), (4094, 4095), (2047, 2048)] {
        let cover = ggm::cover(a, b, depth);
        let (commits, proof) = t.prove::<Sha2>(a, b);
        windows.push(json!({
            "first": a, "last": b,
            "cover": cover.iter().map(|n| json!({"level": n.level, "index": n.index, "value": hx(&t.nodes[n.level as usize][n.index as usize])})).collect::<Vec<_>>(),
            "commits": commits.iter().map(|c| hx(c)).collect::<Vec<_>>(),
            "proof": proof.iter().map(|c| hx(c)).collect::<Vec<_>>(),
        }));
    }

    let mut entries: Vec<Value> = Vec::new();
    for i in 0..12u64 {
        let slot = (r.next() % 4096) as u32;
        let seq = r.next() % 100_000;
        let qty = (r.next() % 2_000_000_000) as i64 - 1_000_000_000;
        let fill = r.next() % 500_000_000_000;
        let note = format!("entry {i}: note with some length").into_bytes();
        let e = Entry { feed: (i % 4) as u8, flags: (i % 2) as u8, qty_e8: qty, fill_e8: fill, settlement: [i as u8; 32], note };
        let leaf = t.nodes[depth as usize][slot as usize];
        let (ct, tag) = entry::encrypt::<Sha2>(&leaf, seq, slot, &e);
        entries.push(json!({
            "slot": slot, "seq": seq, "feed": e.feed, "flags": e.flags, "qty_e8": e.qty_e8.to_string(), "fill_e8": e.fill_e8.to_string(),
            "settlement": hx(&e.settlement), "note": String::from_utf8(e.note.clone()).unwrap(),
            "leaf": hx(&leaf), "key": hx(&entry::entry_key::<Sha2>(&leaf, seq)), "plaintext": hx(&e.encode()), "ct": hx(&ct), "tag": hx(&tag),
        }));
    }

    let mut wraps: Vec<Value> = Vec::new();
    for i in 0..3u64 {
        let shared = [i as u8 + 1; 32];
        let eph = [i as u8 + 40; 32];
        let buyer = [i as u8 + 80; 32];
        let key = entry::wrap_key::<Sha2>(&shared, &eph, &buyer, 1000 + i);
        let mut node = [i as u8 + 120; 32];
        let plain = node;
        entry::wrap_xor(&key, i as u32, &mut node);
        wraps.push(json!({"shared": hx(&shared), "eph": hx(&eph), "buyer": hx(&buyer), "token": 1000 + i, "position": i, "key": hx(&key), "node": hx(&plain), "wrapped": hx(&node)}));
    }

    let mut books: Vec<Value> = Vec::new();
    for case in 0..24 {
        let feeds = 1 + (case % MAX_FEEDS);
        let book_e6: i128 = 10_000_000_000 + (r.next() % 90_000_000_000) as i128;
        let mut b = Book::default();
        let mut trades: Vec<Value> = Vec::new();
        for _ in 0..(20 + case * 3) {
            let feed = (r.next() % 5) as usize;
            let mut qty = (r.next() % 400_000_000) as i64 - 200_000_000;
            if r.next() % 7 == 0 {
                qty *= 100_000; // sometimes far over the limit: must be void
            }
            let price = 100_000_000 + (r.next() % 400_000_000_000) as i64;
            let applied = b.apply(feed, qty, price, feeds, book_e6);
            trades.push(json!({"feed": feed, "qty_e8": qty.to_string(), "price_e8": price.to_string(), "applied": applied, "cash_e16": b.cash_e16.to_string()}));
        }
        let mut marks = [None; MAX_FEEDS];
        let mut json_marks = Vec::new();
        for m in marks.iter_mut() {
            let v = 100_000_000 + (r.next() % 400_000_000_000) as i64;
            *m = Some(v);
            json_marks.push(v.to_string());
        }
        let total = b.marked_e16(&marks).unwrap();
        books.push(json!({
            "feeds": feeds, "book_usd_e6": book_e6.to_string(), "trades": trades, "marks_e8": json_marks,
            "positions": b.positions.iter().map(|p| p.to_string()).collect::<Vec<_>>(),
            "applied": b.applied, "void": b.void, "total_e16": total.to_string(), "pnl_e6": pnl_e6(total).to_string(),
        }));
    }

    let v = json!({
        "note": "Generated by contracts/core/examples/vectors.rs. lib/test/vectors.test.ts holds the TypeScript twin to it.",
        "seed": hx(&seed), "depth": depth, "root": hx(&t.root()),
        "windows": windows, "entries": entries, "wraps": wraps, "books": books,
        "nodes": { "level_1_0": hx(&t.nodes[1][0]), "level_1_1": hx(&t.nodes[1][1]), "level_2_3": hx(&t.nodes[2][3]), "leaf_17": hx(&t.nodes[depth as usize][17]) },
    });
    println!("{}", serde_json::to_string(&v).unwrap());
}
